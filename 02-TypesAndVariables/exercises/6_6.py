# A program that prints numerical representations (codes) of characters.

# double quotes inside the f-string, because the f-string itself uses single quotes
print(f'a {ord("a")}')
print(f'b {ord("b")}')
print(f'z {ord("z")}')
print(f'A {ord("A")}')
print(f'B {ord("B")}')
print(f'Z {ord("Z")}')
print(f'1 {ord("1")}')
print(f'= {ord("=")}')
print(f'+ {ord("+")}')
print(f'€ {ord("€")}')
