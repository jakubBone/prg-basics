# A program that shows two basic for loops: over the characters of a string and over numbers from range().

# for takes the string character by character
city = 'Krakow'
for char in city:
    print(char)

# range(5) gives the numbers 0, 1, 2, 3, 4 (the end 5 is not included)
for i in range(5):
    print(i)
